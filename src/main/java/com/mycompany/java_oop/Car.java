package com.mycompany.java_oop;

/**
 * A class is a blueprint. This one describes what a "Car" is.
 * See LEARN_OOP.md — section 1: Classes and Objects.
 */
public class Car {

    // Fields: information one car can hold (each object gets its own copy).
    int speed;
    String model;

    // A method: something a car can *do*.
    void drive() {
        System.out.println("Driving ...");
    }

}
